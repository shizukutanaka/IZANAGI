//! Kickstart 自動インストール応答ファイル(`*.ks`)の認識と計数。
//!
//! Kickstart は列0始まりのコマンド行(`install`/`url`/`repo`/`lang`/
//! `keyboard`/`network`/`rootpw`/`user`/`group`/`timezone`/`bootloader`/
//! `zerombr`/`clearpart`/`part`/`autopart`/`reqpart`/`volgroup`/`logvol`/
//! `raid`/`btrfs`/`firewall`/`selinux`/`services`/`xconfig`/`skipx`/`text`/
//! `graphical`/`reboot`/`halt`/`poweroff`/`firstboot`/`auth`/`authselect`/
//! `sshpw`/`iscsi`/`fcoe`/`ignoredisk`/`eula`/`timesource`/`rhsm`/
//! `syspurpose`/`zipl`/`mount`/`snapshot`/`nvdimm`/`driverdisk`/`device`/
//! `dmraid`/`multipath`/`zfcp`/`cdrom`/`harddrive`/`nfs`/`liveimg`/
//! `ostreesetup`/`ostreecontainer`/`logging`/`realm`/`sshpubkey`)と
//! `%packages`/`%end`/`%pre`/`%post`/`%pre-install`/`%addon`/`%include`/
//! `%ksappend`/`%anaconda`/`%onerror`/`%traceback` セクション、
//! `--opt=value`/`--opt value` オプション、`#` コメントで構成される。
//! `%packages`〜`%end` 内はパッケージ指定(`@group`/`pkg`/`^env`/`-pkg`)。
//!
//! ```
//! let b = b"# generated by anaconda\nlang en_US.UTF-8\nkeyboard us\ntimezone UTC --utc\nrootpw --iscrypted $6$x\nbootloader --location=mbr\nclearpart --all --initlabel\npart / --fstype=xfs --size=1024 --grow\n%packages\n@core\nvim-enhanced\n-git\n%end\n%post --interpreter=/bin/bash\nsystemctl enable sshd\n%end\n";
//! assert!(izanagi_kit::kickstart::detect(b));
//! let c = izanagi_kit::kickstart::parse(b).unwrap();
//! assert_eq!(c.commands, 7); // lang/keyboard/timezone/rootpw/bootloader/clearpart/part
//! assert_eq!(c.options, 9); // コマンド行 8 + %post の --interpreter
//! assert_eq!(c.sections, 2); // %packages + %post(%end は含めない)
//! assert_eq!(c.packages, 3); // @core/vim-enhanced/-git
//! ```

/// [`parse`] が返す計数。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Counts {
    /// 列0コマンド行(`lang`/`part` 等)の個数。
    pub commands: usize,
    /// `%packages`〜`%end` 等セクションマーカの個数(`%xxx` 行、`%end` 除く)。
    pub sections: usize,
    /// `%packages` ブロック内のパッケージ指定行の個数。
    pub packages: usize,
    /// `--opt`/`--opt=value` オプショントークンの総数。
    pub options: usize,
    /// スクリプト行(`%pre`/`%post`/`%onerror`/`%traceback` ブロック内)の個数。
    pub script_lines: usize,
    /// `#` コメント行の個数。
    pub comments: usize,
}

