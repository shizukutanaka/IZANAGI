const SECTION_HEADS: &[&str] = &[
    "%packages",
    "%pre",
    "%post",
    "%pre-install",
    "%addon",
    "%anaconda",
    "%onerror",
    "%traceback",
    "%ksappend",
    "%include",
    "%end",
];

fn section_tag(s: &str) -> Option<&str> {
    SECTION_HEADS.iter().find(|h| s.starts_with(*h)).copied()
}
fn strip_bom(t: &str) -> &str {
    t.strip_prefix('\u{feff}').unwrap_or(t)
}

/// Kickstart らしさを返す。既知コマンド行 ≥2、または `%packages`。
#[must_use]
pub fn detect(b: &[u8]) -> bool {
    let Ok(t) = std::str::from_utf8(b) else {
        return false;
    };
    let t = strip_bom(t);
    let mut hits = 0usize;
    for l in t.lines() {
        let s = l.trim();
        if s.is_empty() || s.starts_with('#') {
            continue;
        }
        if s.starts_with("%packages") {
            return true;
        }
        let head = s.split_whitespace().next().unwrap_or("");
        if COMMANDS.contains(&head) {
            hits += 1;
        }
    }
    hits >= 2
}

/// ファイル全体を走査して [`Counts`] を返す。
#[must_use]
pub fn parse(b: &[u8]) -> Option<Counts> {
    let t = std::str::from_utf8(b).ok()?;
    let t = strip_bom(t);
    let mut c = Counts {
        commands: 0,
        sections: 0,
        packages: 0,
        options: 0,
        script_lines: 0,
        comments: 0,
    };
    // 0=コマンド部, 1=packages, 2=script(pre/post/onerror/traceback), 3=addon(無視)
    let mut state = 0u8;
    for l in t.lines() {
        let s = l.trim();
        if s.is_empty() {
            continue;
        }
        if s.starts_with('#') {
            c.comments += 1;
            continue;
        }
        if let Some(h) = section_tag(s) {
            match h {
                "%end" => state = 0,
                "%packages" => {
                    c.sections += 1;
                    state = 1;
                }
                "%pre" | "%post" | "%pre-install" | "%onerror" | "%traceback" => {
                    c.sections += 1;
                    state = 2;
                    for tok in s.split_whitespace() {
                        if tok.starts_with("--") {
                            c.options += 1;
                        }
                    }
                }
                _ => {
                    c.sections += 1;
                }
            }
            continue;
        }
        match state {
            1 => c.packages += 1,
            2 => c.script_lines += 1,
            _ => {
                let head = s.split_whitespace().next().unwrap_or("");
                if COMMANDS.contains(&head) {
                    c.commands += 1;
                    for tok in s.split_whitespace() {
                        if tok.starts_with("--") {
                            c.options += 1;
                        }
                    }
                } else {
                    // 継続・生テキスト行もオプション混入可(保守的に数えない)
                }
            }
        }
    }
    Some(c)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn detects() {
        assert!(detect(b"lang en_US.UTF-8\nkeyboard us\ntimezone UTC\n"));
        assert!(detect(b"%packages\n@core\n%end\n"));
    }

    #[test]
    fn rejects() {
        assert!(!detect(b"foo bar\nbaz qux\n"));
        assert!(!detect(&[0xff]));
    }

    #[test]
    fn counts() {
        let b = b"lang en_US\npart / --fstype=xfs --size=1024\n%packages\n@core\nvim\n%end\n%post\necho hi\n%end\n";
        let c = parse(b).unwrap();
        assert_eq!(c.commands, 2);
        assert_eq!(c.sections, 2);
        assert_eq!(c.packages, 2);
        assert_eq!(c.options, 2);
        assert_eq!(c.script_lines, 1);
    }

    #[test]
    fn copy_eq() {
        let c = parse(b"lang en_US\n").unwrap();
        let d = c;
        assert_eq!(c, d);
    }

    #[test]
    fn utf8_bom_is_tolerated() {
        assert_eq!(strip_bom("\u{feff}x"), "x");
        assert_eq!(strip_bom("x"), "x");
    }
}
